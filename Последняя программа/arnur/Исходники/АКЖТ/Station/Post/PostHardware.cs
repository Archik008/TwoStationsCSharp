public static class PostHardware
{
    public static HardwareMap Build()
    {
        var m = new HardwareMap();

        // [ИЗМЕНЕНО 28.10.2026] лампы светофоров поста — в общей карте АКЖТ (AkzhtHardware.cs, файл светофоры.txt)

        // ---------- стрелки: пара → каналы PCA9685 ----------
        // [ИЗМЕНЕНО 28.10.2026] по документу «Серво станции АКЖТ» (пакет 27.10.2026, скетч StationMain_AKZHT):
        //   канал 14 → стрелка 1, 1 → 2, 0 → 3, 2 → 4. Было: 3/4 → канал 1, 1/2 — без серво.
        m.Servos["1/2"] = new[] { 14, 1 };
        m.Servos["3/4"] = new[] { 0, 2 };

        // ---------- датчики занятости: участок → бит строки "Data:" (0 = младший) ----------
        // Пока ни одного — участки занимаются ПКМ или виртуальным поездом. Пример:
        // m.Sensors["2-3СП"] = 3;

        return m;
    }
}
