using StationApp.Core;

namespace StationApp.Post;

// =====================================================================
//  КАРТА "ПРОВОДОВ" ПУТЕВОГО ПОСТА: стрелки и датчики.
//  [ИЗМЕНЕНО 28.10.2026] Лампы светофоров поста — по таблице распиновки в AkzhtHardware.cs
//  (файл светофоры.txt рядом с Station.exe): плата у АКЖТ и поста одна.
