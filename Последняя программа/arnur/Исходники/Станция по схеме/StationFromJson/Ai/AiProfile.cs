    public static string HelpExampleKk => Lay?.Examples().helpKk ?? "басталу светофоры, содан кейін жол.";

    /// <summary>Чей объект схемы: у станции из файла все объекты — свои (соседей пока нет).</summary>
    public static string StationOf(string id, AiLang l) => Station;

