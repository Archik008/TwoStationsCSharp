public static class AiProfile
{
    static Scheme.JsonLayout Lay => ModelHost.Model?.Layout;

    public static string Station => Lay?.Name ?? "по схеме";

    public static string KnowledgeFolder
    {
        get
        {
            var safe = Regex.Replace(Station, @"[\\/:*?""<>|]+", "_").Trim();
            return Path.Combine(AppContext.BaseDirectory, "Knowledge", safe.Length > 0 ? safe : "станция");
        }
    }

    public static string RouteExampleRu => Lay?.Examples().ru ?? "маршрут Ч на путь 1";
    public static string RouteExampleKk => Lay?.Examples().kk ?? "Ч-дан 1 жолға маршрут";
