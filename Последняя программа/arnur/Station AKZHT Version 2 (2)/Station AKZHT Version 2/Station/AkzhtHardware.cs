using StationApp.Core;

namespace StationApp;

// =====================================================================
//  КАРТА "ПРОВОДОВ" СТАНЦИИ АКЖТ (плата АКЖТ; на ней же путевой пост — см. Post/PostHardware.cs)
//
//  Лампы: (светофор, лампа) → (номер байта, номер бита). 0 бит = лампа ГОРИТ (Active-Low).
//  По проекту на АКЖТ будет 3 платы по 5 регистров = 15 байт = 120 ламп. Сейчас на плате АКЖТ
//  стоят 2 регистра 74HC595 (пины 13/12/11), прошивка AKZHT_Main принимает 5 байт
//  (ArduinoLink.FrameBytes = 5) — на лампы реально попадают байты 0 и 1. Биты в байтах 5..14
//  уже расписаны (ЗАГОТОВКА). Когда поставят платы — поменять FrameBytes на 15
//  и в прошивке LIGHT_BYTES на 15.
//
//  Что взято из реальной распайки (Python AKZHT_UI/ArduinoCode.py): байт 0 и биты 0..4 байта 1
//  (Н, Ч1..Ч5). Всё остальное — ВРЕМЕННЫЕ номера, их нужно сверить с платой.
// =====================================================================

public static class AkzhtHardware
{
    public static HardwareMap Build(bool depot)
    {
        var m = new HardwareMap();
        void L(string sig, string lamp, int b, int bit) => m.Lamps[("А:" + sig, lamp)] = (b, bit);

        // ---------- из реальной распайки (Python AKZHT_UI) ----------
        L("Н", "red", 0, 0);
        L("Н", "yellow", 0, 1);
        L("Н", "yellow1", 0, 2);
        L("Ч1", "red", 0, 3);
        L("Ч1", "green", 0, 4);
        L("Ч2", "red", 0, 5);
        L("Ч2", "green", 0, 6);
        L("Ч3", "red", 0, 7);
        L("Ч3", "green", 1, 0);
        L("Ч4", "red", 1, 1);
        L("Ч4", "green", 1, 2);
        L("Ч5", "red", 1, 3);
        L("Ч5", "green", 1, 4);
        // (1,5) в Python занят "H_fake" — оставлен свободным.
        // (1,6)..(4,7) — путевой пост (Post/PostHardware.cs).

        // ---------- ЗАГОТОВКА: платы 2 и 3 (байты 5..14), пока не отправляются ----------
        int b = 5, bit = 0;
        void Next(string sig, string lamp)
        {
            L(sig, lamp, b, bit);
            if (++bit == 8) { bit = 0; b++; }
        }
        // недостающие лампы входного Н и выходных Ч
        Next("Н", "green"); Next("Н", "white");
        foreach (var c in new[] { "Ч1", "Ч2", "Ч3", "Ч4", "Ч5" }) { Next(c, "yellow"); Next(c, "white"); }
        // входной Ч (левая горловина)
        foreach (var lamp in new[] { "yellow", "green", "red", "yellow1", "white" }) Next("Ч", lamp);
        // выходные Н1..Н5 (левая горловина)
        foreach (var h in new[] { "Н1", "Н2", "Н3", "Н4", "Н5" })
            foreach (var lamp in new[] { "yellow", "green", "red", "white" }) Next(h, lamp);
        // маневровые
        foreach (var mm in new[] { "М1", "М2", "М3", "М4", "М5", "М6", "М7", "М8" }) { Next(mm, "white"); Next(mm, "blue"); }
        Next("М10", "white"); Next("М10", "red");
        if (depot) { Next("М9", "white"); Next("М9", "red"); }

        // ---------- стрелки: пара → каналы PCA9685 (из Python SWITCH_HW_MAP) ----------
        // "AKZHT_Turn5-7" → W 4 и W 5; "AKZHT_Turn1-3" → W 6 и W 3; "AKZHT_Turn19" → W 7; "AKZHT_Turn13-15" → W 8 и W 15
        m.Servos["А:5/7"] = new[] { 4, 5 };
        m.Servos["А:1/3"] = new[] { 6, 3 };
        m.Servos["А:19"] = new[] { 7 };
        m.Servos["А:13/15"] = new[] { 8, 15 };   // каналы 8 и 15 (прошивка АКЖТ знает все 16 каналов 0..15)
        // стрелка 17 и вся левая горловина физически пока без сервоприводов — ЗАГОТОВКА:
        m.Servos["А:17"] = Array.Empty<int>();
        m.Servos["А:2/4"] = Array.Empty<int>();
        m.Servos["А:6/8"] = Array.Empty<int>();
        m.Servos["А:10/12"] = Array.Empty<int>();
        m.Servos["А:14"] = Array.Empty<int>();
        m.Servos["А:16"] = Array.Empty<int>();

        // ---------- датчики занятости ----------
        // [ИЗМЕНЕНО 06.10.2026] Сейчас на АКЖТ работают 2 детектора, их выходы "Занятость"
        // подключены ПРЯМО к пинам Arduino (плата 74HC165 пока не подключена):
        //     пин 10 → участок Н-М1 (между входным Н и М1)
        //     пин 8  → участок УII  (от М3 до проходного 6)
        //     пин 9  → резерв (3-й символ)
        // Так было и в старой рабочей прошивке АКЖТ (проверено по резервной копии .hex и по Python
        // AKZHT_UI: SEGMENT_ORDER = [("M1","H"), ("M3","6")]). В версии 3 у меня пины 8 и 10 были
        // перепутаны — вы это заметили и поменяли в скетче; теперь исправлено здесь и в AKZHT_Main.
        // Прошивка AKZHT_Main присылает "Occ: 101": 1-й символ — пин 10, 2-й — пин 8, 3-й — пин 9.
        m.PinSensors["А:Н-М1"] = 0;   m.PinNames[0] = "пин 10";
        m.PinSensors["А:УII"] = 1;    m.PinNames[1] = "пин 8";

        // Старая привязка к строке "Data:" (плата 74HC165) отключена: плата сейчас не подключена,
        // и из "Data:" приходил бы случайный мусор → ложная занятость. Когда 165-ю плату подключат,
        // записать сюда: m.Sensors["А:<участок>"] = <номер бита>;   (0 = последний символ строки "Data:")

        return m;
    }
}
