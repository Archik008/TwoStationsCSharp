(Этот файл начинается с «_», поэтому студенческий помощник его НЕ читает.)

Куда класть: в эту папку (Knowledge, рядом с файлом Station.sln).
Формат: обычные текстовые файлы.txt или .md в кодировке UTF-8. Word/PDF не читаются —
скопируйте текст в .txt. Помощник подхватывает новые файлы сам, перезапуск не нужен.

В студенческом режиме помощник отвечает ТОЛЬКО по этим файлам, поэтому важно,
чтобы правила и нормативы были написаны здесь вашими словами или цитатами из документов,
которые вы сами проверили. Если в материалах чего-то нет, помощник скажет «уточните у преподавателя».

РЕКОМЕНДУЕМАЯ СТРУКТУРА (один файл = одна тема, коротко, 1–2 страницы):

  Глоссарий.txt         — «Термин — определение простыми словами». Одна запись = 1–3 строки.
  Маршруты_и_стрелки.txt — как задаётся маршрут, что проверяется перед открытием светофора.
  Сигналы.txt           — значения огней светофоров на макете.
  Типичные_ошибки.txt   — «Ошибка → к чему приводит → как исправить».
  Задания.txt           — текст практических заданий (что должен сделать студент).
  Участки_станции.txt   — что означают названия участков и стрелок на схеме (5БУ, НУ, 1СП, Тун ...).

ШАБЛОН ЗАПИСИ (замените текст в [скобках] своим):

  Термин: [название]
Определение: [одно-два предложения простыми словами]
  Пример на макете: [где это видно на схеме станции]

Ошибка: [что сделал студент]
К чему приводит: [последствие]
Как исправить: [действия по шагам]

Советы:
  • Пишите конкретно и короткими абзацами — помощник ищет по ключевым словам.
  • Называйте участки и стрелки так же, как на схеме (4СП, НАУ, Стр. 1/2).
  • Не копируйте целые документы: берите только то, что нужно студентам на занятии.
  • Для казахского языка можно писать материалы на любом из двух языков — помощник ответит на языке вопроса.

РЕЖИМЫ (вводятся в строке чата):
  / teacher < пароль >  — режим преподавателя(поиск по всему проекту, включая код)
  / student           — вернуться в студенческий режим
  Пароль по умолчанию «teacher» — ОБЯЗАТЕЛЬНО смените: переменная среды AKZHT_TEACHER_PASSWORD
  или константа в AiAssistant.cs./*